-- 006: in-app notifications per account.
CREATE TABLE pp_notifications (
    id         NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    account_id NUMBER(19) NOT NULL,
    category   VARCHAR2(20 CHAR)   NOT NULL,
    title      VARCHAR2(160 CHAR)  NOT NULL,
    body       VARCHAR2(1000 CHAR) NOT NULL,
    link       VARCHAR2(200 CHAR),
    channels   VARCHAR2(40 CHAR),
    read_at    TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_pp_notifications PRIMARY KEY (id),
    CONSTRAINT fk_pp_notif_account FOREIGN KEY (account_id) REFERENCES agent_account (id)
);

CREATE INDEX ix_pp_notif_account ON pp_notifications (account_id, created_at);
