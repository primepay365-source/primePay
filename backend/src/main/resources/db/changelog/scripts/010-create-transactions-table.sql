-- 010: every money movement (load, bill payment, add funds, withdrawal, commission, reversal, adjustment),
-- plus the sequence behind human-readable reference numbers.
CREATE SEQUENCE pp_txn_ref_seq START WITH 1000 INCREMENT BY 1;

CREATE TABLE pp_transactions (
    id                        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    reference_no              VARCHAR2(30 CHAR) NOT NULL,
    txn_type                  VARCHAR2(20 CHAR) NOT NULL,
    status                    VARCHAR2(20 CHAR) NOT NULL,
    service_code              VARCHAR2(30 CHAR) NOT NULL,
    initiator_account_id      NUMBER(19) NOT NULL,
    source_account_id         NUMBER(19),
    target_account_id         NUMBER(19),
    amount                    NUMBER(19,2) NOT NULL,
    fee                       NUMBER(19,2) DEFAULT 0 NOT NULL,
    idempotency_key           VARCHAR2(80 CHAR),
    request_hash              VARCHAR2(64 CHAR),
    original_txn_id           NUMBER(19),
    remarks                   VARCHAR2(300 CHAR),
    external_ref              VARCHAR2(80 CHAR),
    payout_mode               VARCHAR2(10 CHAR),
    beneficiary_name          VARCHAR2(160 CHAR),
    beneficiary_account_last4 VARCHAR2(4 CHAR),
    beneficiary_ifsc          VARCHAR2(11 CHAR),
    beneficiary_bank          VARCHAR2(120 CHAR),
    biller_name               VARCHAR2(120 CHAR),
    customer_name             VARCHAR2(160 CHAR),
    card_last4                VARCHAR2(4 CHAR),
    card_network              VARCHAR2(20 CHAR),
    gateway_category          VARCHAR2(20 CHAR),
    customer_mobile_masked    VARCHAR2(20 CHAR),
    failure_reason            VARCHAR2(300 CHAR),
    decided_by_account_id     NUMBER(19),
    created_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    version                   NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_pp_transactions PRIMARY KEY (id),
    CONSTRAINT uq_pp_txn_reference UNIQUE (reference_no),
    CONSTRAINT uq_pp_txn_idempotency UNIQUE (initiator_account_id, idempotency_key),
    CONSTRAINT fk_pp_txn_initiator FOREIGN KEY (initiator_account_id) REFERENCES agent_account (id),
    CONSTRAINT ck_pp_txn_amount CHECK (amount > 0 AND fee >= 0),
    CONSTRAINT ck_pp_txn_status CHECK (status IN ('INITIATED', 'PENDING', 'SUCCESS', 'FAILED', 'REVERSED', 'REFUNDED'))
);

CREATE INDEX ix_pp_txn_created ON pp_transactions (created_at);
CREATE INDEX ix_pp_txn_initiator ON pp_transactions (initiator_account_id, created_at);
CREATE INDEX ix_pp_txn_status ON pp_transactions (status);
