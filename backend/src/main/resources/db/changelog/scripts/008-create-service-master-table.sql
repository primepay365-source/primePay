-- 008: services the platform offers, their flat fee and on/off switch (editable by the Platform Admin).
CREATE TABLE pp_service_master (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    service_code VARCHAR2(30 CHAR) NOT NULL,
    name         VARCHAR2(80 CHAR) NOT NULL,
    fee_amount   NUMBER(19,2) DEFAULT 0 NOT NULL,
    enabled      BOOLEAN DEFAULT TRUE NOT NULL,
    provider     VARCHAR2(80 CHAR),
    CONSTRAINT pk_pp_service_master PRIMARY KEY (id),
    CONSTRAINT uq_pp_service_code UNIQUE (service_code)
);

