-- 007: one-time codes, stored only as BCrypt hashes. LOGIN = second sign-in step, PASSWORD_RESET = reset.
-- challenge_ref is the opaque id the browser holds between sign-in steps (never the code itself).
CREATE TABLE pp_otp_verifications (
    id                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    account_id         NUMBER(19) NOT NULL,
    purpose            VARCHAR2(30 CHAR) NOT NULL,
    challenge_ref      VARCHAR2(64 CHAR),
    channel            VARCHAR2(10 CHAR),
    destination_masked VARCHAR2(80 CHAR),
    code_hash          VARCHAR2(100 CHAR) NOT NULL,
    attempts           NUMBER(10) DEFAULT 0 NOT NULL,
    resend_count       NUMBER(10) DEFAULT 0 NOT NULL,
    ip_address         VARCHAR2(64 CHAR),
    expires_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at        TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_pp_otp PRIMARY KEY (id),
    CONSTRAINT uq_pp_otp_challenge UNIQUE (challenge_ref),
    CONSTRAINT fk_pp_otp_account FOREIGN KEY (account_id) REFERENCES agent_account (id),
    CONSTRAINT ck_pp_otp_channel CHECK (channel IS NULL OR channel IN ('EMAIL', 'SMS'))
);

CREATE INDEX ix_pp_otp_account ON pp_otp_verifications (account_id, purpose);
