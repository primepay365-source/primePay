-- 005: append-only audit trail of sign-ins, user changes and money movements.
CREATE TABLE pp_audit_logs (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    occurred_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_account_id NUMBER(19),
    actor_label      VARCHAR2(160 CHAR),
    action           VARCHAR2(60 CHAR) NOT NULL,
    target_type      VARCHAR2(40 CHAR),
    target_id        VARCHAR2(80 CHAR),
    result           VARCHAR2(20 CHAR) NOT NULL,
    detail           VARCHAR2(4000 CHAR),
    ip_address       VARCHAR2(64 CHAR),
    request_id       VARCHAR2(64 CHAR),
    CONSTRAINT pk_pp_audit_logs PRIMARY KEY (id)
);

CREATE INDEX ix_pp_audit_time ON pp_audit_logs (occurred_at);
CREATE INDEX ix_pp_audit_actor ON pp_audit_logs (actor_account_id);
