-- 009: one main wallet per account. Balances change only through the ledger and are never negative.
CREATE TABLE pp_wallets (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    wallet_code       VARCHAR2(40 CHAR) NOT NULL,
    account_id        NUMBER(19) NOT NULL,
    available_balance NUMBER(19,2) DEFAULT 0 NOT NULL,
    blocked_balance   NUMBER(19,2) DEFAULT 0 NOT NULL,
    total_credit      NUMBER(19,2) DEFAULT 0 NOT NULL,
    total_debit       NUMBER(19,2) DEFAULT 0 NOT NULL,
    status            VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    version           NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_pp_wallets PRIMARY KEY (id),
    CONSTRAINT uq_pp_wallet_code UNIQUE (wallet_code),
    CONSTRAINT uq_pp_wallet_account UNIQUE (account_id),
    CONSTRAINT fk_pp_wallet_account FOREIGN KEY (account_id) REFERENCES agent_account (id),
    CONSTRAINT ck_pp_wallet_nonneg CHECK (available_balance >= 0 AND blocked_balance >= 0)
);
