-- 004: every status change of an account, with who changed it and why.
CREATE TABLE pp_user_status_history (
    id                    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    account_id            NUMBER(19) NOT NULL,
    from_status           VARCHAR2(30 CHAR),
    to_status             VARCHAR2(30 CHAR) NOT NULL,
    reason                VARCHAR2(500 CHAR),
    changed_by_account_id NUMBER(19),
    changed_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_pp_user_status_history PRIMARY KEY (id),
    CONSTRAINT fk_pp_ush_account FOREIGN KEY (account_id) REFERENCES agent_account (id)
);

CREATE INDEX ix_pp_ush_account ON pp_user_status_history (account_id, changed_at);
