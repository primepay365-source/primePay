-- 003: distributor onboarding application (5-step form) and the approver's decision.
CREATE TABLE distributor_onboarding (
    id                       NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    distributor_account_id   NUMBER(19) NOT NULL,
    created_by_account_id    NUMBER(19) NOT NULL,
    full_name                VARCHAR2(160 CHAR) NOT NULL,
    mobile                   VARCHAR2(20 CHAR)  NOT NULL,
    email                    VARCHAR2(160 CHAR) NOT NULL,
    address                  VARCHAR2(500 CHAR) NOT NULL,
    photo_content_type       VARCHAR2(100 CHAR) NOT NULL,
    photo_data               BLOB NOT NULL,
    kyc_document_type        VARCHAR2(32 CHAR)  NOT NULL,
    kyc_last_four            VARCHAR2(4 CHAR)   NOT NULL,
    bank_account_holder      VARCHAR2(160 CHAR) NOT NULL,
    bank_name                VARCHAR2(120 CHAR) NOT NULL,
    bank_ifsc                VARCHAR2(11 CHAR)  NOT NULL,
    bank_account_last_four   VARCHAR2(4 CHAR)   NOT NULL,
    velocity_per_transaction NUMBER(18,2) NOT NULL,
    velocity_daily           NUMBER(18,2) NOT NULL,
    commission_payin         NUMBER(5,2)  NOT NULL,
    commission_payout        NUMBER(5,2)  NOT NULL,
    commission_bill_payment  NUMBER(5,2)  NOT NULL,
    agreement_version        VARCHAR2(40 CHAR) NOT NULL,
    agreement_accepted_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    status                   VARCHAR2(24 CHAR) NOT NULL,
    submitted_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_by_account_id    NUMBER(19),
    decided_at               TIMESTAMP WITH TIME ZONE,
    decision_note            VARCHAR2(500 CHAR),
    CONSTRAINT pk_distributor_onboarding PRIMARY KEY (id),
    CONSTRAINT uq_distributor_onboarding_account UNIQUE (distributor_account_id),
    CONSTRAINT fk_onboarding_distributor FOREIGN KEY (distributor_account_id) REFERENCES agent_account (id),
    CONSTRAINT fk_onboarding_creator FOREIGN KEY (created_by_account_id) REFERENCES agent_account (id),
    CONSTRAINT ck_onboarding_status CHECK (status IN ('SUBMITTED', 'APPROVED', 'REJECTED'))
);
