-- 013: manual wallet corrections with maker-checker: the approver must be a different admin.
CREATE TABLE pp_wallet_adjustments (
    id                      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    request_ref             VARCHAR2(30 CHAR) NOT NULL,
    account_id              NUMBER(19) NOT NULL,
    direction               VARCHAR2(2 CHAR)  NOT NULL,
    amount                  NUMBER(19,2) NOT NULL,
    reason                  VARCHAR2(80 CHAR) NOT NULL,
    details                 VARCHAR2(500 CHAR),
    status                  VARCHAR2(20 CHAR) NOT NULL,
    requested_by_account_id NUMBER(19) NOT NULL,
    decided_by_account_id   NUMBER(19),
    decided_at              TIMESTAMP WITH TIME ZONE,
    transaction_id          NUMBER(19),
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_pp_adjustments PRIMARY KEY (id),
    CONSTRAINT uq_pp_adj_ref UNIQUE (request_ref),
    CONSTRAINT fk_pp_adj_account FOREIGN KEY (account_id) REFERENCES agent_account (id),
    CONSTRAINT ck_pp_adj_maker_checker CHECK (decided_by_account_id IS NULL OR decided_by_account_id <> requested_by_account_id)
);
