-- 017: billers for bill payment (credit card issuers).
CREATE TABLE pp_billers (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    category    VARCHAR2(30 CHAR)  NOT NULL,
    biller_code VARCHAR2(30 CHAR)  NOT NULL,
    name        VARCHAR2(120 CHAR) NOT NULL,
    enabled     BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT pk_pp_billers PRIMARY KEY (id),
    CONSTRAINT uq_pp_biller_code UNIQUE (biller_code)
);

