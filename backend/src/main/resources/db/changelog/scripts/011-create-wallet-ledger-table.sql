-- 011: append-only double-entry ledger: every debit (DR) and credit (CR) with the balance before and after.
CREATE TABLE pp_wallet_ledger (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    entry_ref      VARCHAR2(40 CHAR) NOT NULL,
    wallet_id      NUMBER(19) NOT NULL,
    transaction_id NUMBER(19) NOT NULL,
    direction      VARCHAR2(2 CHAR)  NOT NULL,
    entry_type     VARCHAR2(30 CHAR) NOT NULL,
    amount         NUMBER(19,2) NOT NULL,
    balance_before NUMBER(19,2) NOT NULL,
    balance_after  NUMBER(19,2) NOT NULL,
    description    VARCHAR2(300 CHAR),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_pp_wallet_ledger PRIMARY KEY (id),
    CONSTRAINT uq_pp_ledger_ref UNIQUE (entry_ref),
    CONSTRAINT fk_pp_ledger_wallet FOREIGN KEY (wallet_id) REFERENCES pp_wallets (id),
    CONSTRAINT fk_pp_ledger_txn FOREIGN KEY (transaction_id) REFERENCES pp_transactions (id),
    CONSTRAINT ck_pp_ledger_dir CHECK (direction IN ('DR', 'CR') AND amount > 0)
);

CREATE INDEX ix_pp_ledger_wallet ON pp_wallet_ledger (wallet_id, created_at);
CREATE INDEX ix_pp_ledger_txn ON pp_wallet_ledger (transaction_id);
