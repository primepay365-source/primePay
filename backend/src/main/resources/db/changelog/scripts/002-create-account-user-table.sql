-- 002: sign-in credentials (BCrypt hash only) and lockout state; one per account.
CREATE TABLE account_user (
    id                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    username            VARCHAR2(80 CHAR)  NOT NULL,
    password_hash       VARCHAR2(100 CHAR) NOT NULL,
    account_id          NUMBER(19) NOT NULL,
    active              BOOLEAN DEFAULT TRUE NOT NULL,
    failed_attempts     NUMBER(10) DEFAULT 0 NOT NULL,
    locked_until        TIMESTAMP WITH TIME ZONE,
    password_changed_at TIMESTAMP WITH TIME ZONE,
    last_login_at       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_account_user PRIMARY KEY (id),
    CONSTRAINT uq_account_user_username UNIQUE (username),
    CONSTRAINT uq_account_user_account UNIQUE (account_id),
    CONSTRAINT fk_account_user_account FOREIGN KEY (account_id) REFERENCES agent_account (id)
);
