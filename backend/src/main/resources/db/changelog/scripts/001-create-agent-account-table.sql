-- 001: every account in the hierarchy (Platform Admin, Super/Master Distributor, Distributor, Retailer).
-- Email and mobile are sign-in identifiers: stored lower-case / as +91XXXXXXXXXX and unique.
CREATE TABLE agent_account (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    account_code  VARCHAR2(40 CHAR)  NOT NULL,
    display_name  VARCHAR2(160 CHAR) NOT NULL,
    role          VARCHAR2(32 CHAR)  NOT NULL,
    parent_id     NUMBER(19),
    active        BOOLEAN DEFAULT TRUE NOT NULL,
    status        VARCHAR2(30 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    email         VARCHAR2(160 CHAR),
    mobile        VARCHAR2(20 CHAR),
    business_name VARCHAR2(160 CHAR),
    address       VARCHAR2(500 CHAR),
    created_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_agent_account PRIMARY KEY (id),
    CONSTRAINT uq_agent_account_code UNIQUE (account_code),
    CONSTRAINT uq_agent_account_email UNIQUE (email),
    CONSTRAINT uq_agent_account_mobile UNIQUE (mobile),
    CONSTRAINT fk_agent_account_parent FOREIGN KEY (parent_id) REFERENCES agent_account (id),
    CONSTRAINT ck_agent_account_role CHECK (role IN ('ADMIN', 'SUPER_DISTRIBUTOR', 'MASTER_DISTRIBUTOR', 'DISTRIBUTOR', 'RETAILER')),
    CONSTRAINT ck_agent_account_status CHECK (status IN ('DRAFT', 'PENDING_VERIFICATION', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'SUSPENDED', 'ACTIVE', 'INACTIVE'))
);

CREATE INDEX ix_agent_account_parent ON agent_account (parent_id);
CREATE INDEX ix_agent_account_role ON agent_account (role);
CREATE INDEX ix_agent_account_status ON agent_account (status);
