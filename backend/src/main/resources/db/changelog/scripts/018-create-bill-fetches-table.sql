-- 018: a fetched bill (card holder, dues), valid for a short time before it must be fetched again.
CREATE TABLE pp_bill_fetches (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    fetch_ref     VARCHAR2(40 CHAR) NOT NULL,
    account_id    NUMBER(19) NOT NULL,
    biller_id     NUMBER(19) NOT NULL,
    card_last4    VARCHAR2(4 CHAR)   NOT NULL,
    mobile_masked VARCHAR2(20 CHAR)  NOT NULL,
    customer_name VARCHAR2(160 CHAR) NOT NULL,
    total_due     NUMBER(19,2) NOT NULL,
    minimum_due   NUMBER(19,2) NOT NULL,
    due_date      TIMESTAMP,
    provider_ref  VARCHAR2(60 CHAR),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_pp_bill_fetches PRIMARY KEY (id),
    CONSTRAINT uq_pp_bill_fetch_ref UNIQUE (fetch_ref),
    CONSTRAINT fk_pp_bf_account FOREIGN KEY (account_id) REFERENCES agent_account (id),
    CONSTRAINT fk_pp_bf_biller FOREIGN KEY (biller_id) REFERENCES pp_billers (id)
);

CREATE INDEX ix_pp_bf_account ON pp_bill_fetches (account_id);
