-- 021: saved bank accounts for withdrawals. The account number is encrypted (AES-GCM) with an HMAC for
-- duplicate checks; only the last 4 digits are ever shown.
CREATE TABLE pp_beneficiaries (
    id                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    account_id         NUMBER(19) NOT NULL,
    holder_name        VARCHAR2(160 CHAR) NOT NULL,
    verified_name      VARCHAR2(160 CHAR),
    account_number_enc VARCHAR2(200 CHAR) NOT NULL,
    account_hash       VARCHAR2(64 CHAR)  NOT NULL,
    account_last4      VARCHAR2(4 CHAR)   NOT NULL,
    ifsc               VARCHAR2(11 CHAR)  NOT NULL,
    bank_name          VARCHAR2(120 CHAR) NOT NULL,
    status             VARCHAR2(20 CHAR)  NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_pp_beneficiaries PRIMARY KEY (id),
    CONSTRAINT fk_pp_ben_account FOREIGN KEY (account_id) REFERENCES agent_account (id)
);

CREATE INDEX ix_pp_ben_account ON pp_beneficiaries (account_id);
