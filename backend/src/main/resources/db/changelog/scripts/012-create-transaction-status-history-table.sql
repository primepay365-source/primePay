-- 012: each status step of a transaction (INITIATED -> PENDING -> SUCCESS / FAILED / REVERSED).
CREATE TABLE pp_transaction_status_history (
    id                    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    transaction_id        NUMBER(19) NOT NULL,
    from_status           VARCHAR2(20 CHAR),
    to_status             VARCHAR2(20 CHAR) NOT NULL,
    note                  VARCHAR2(300 CHAR),
    changed_by_account_id NUMBER(19),
    changed_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_pp_txn_history PRIMARY KEY (id),
    CONSTRAINT fk_pp_txh_txn FOREIGN KEY (transaction_id) REFERENCES pp_transactions (id)
);

CREATE INDEX ix_pp_txh_txn ON pp_transaction_status_history (transaction_id);
