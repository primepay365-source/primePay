-- 014: commission rules (per service), the share per level, and every commission entry paid or reversed.
CREATE TABLE pp_commission_rules (
    id                    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    rule_code             VARCHAR2(30 CHAR) NOT NULL,
    service_code          VARCHAR2(30 CHAR) NOT NULL,
    calc_type             VARCHAR2(10 CHAR) NOT NULL,
    slab_from             NUMBER(19,2),
    slab_to               NUMBER(19,2),
    effective_from        TIMESTAMP NOT NULL,
    effective_to          TIMESTAMP,
    status                VARCHAR2(10 CHAR) NOT NULL,
    created_by_account_id NUMBER(19),
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_pp_comm_rules PRIMARY KEY (id),
    CONSTRAINT uq_pp_comm_rule_code UNIQUE (rule_code)
);

CREATE TABLE pp_commission_distribution (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    rule_id      NUMBER(19) NOT NULL,
    level_role   VARCHAR2(30 CHAR) NOT NULL,
    rate         NUMBER(9,6),
    fixed_amount NUMBER(19,2),
    min_amount   NUMBER(19,2),
    max_amount   NUMBER(19,2),
    CONSTRAINT pk_pp_comm_dist PRIMARY KEY (id),
    CONSTRAINT fk_pp_cd_rule FOREIGN KEY (rule_id) REFERENCES pp_commission_rules (id),
    CONSTRAINT uq_pp_cd_rule_level UNIQUE (rule_id, level_role)
);

CREATE TABLE pp_commission_transactions (
    id                NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    source_txn_id     NUMBER(19) NOT NULL,
    credit_txn_id     NUMBER(19),
    rule_id           NUMBER(19) NOT NULL,
    earner_account_id NUMBER(19),
    level_role        VARCHAR2(30 CHAR) NOT NULL,
    base_amount       NUMBER(19,2) NOT NULL,
    commission_amount NUMBER(19,2) NOT NULL,
    status            VARCHAR2(20 CHAR) NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_pp_comm_txn PRIMARY KEY (id),
    CONSTRAINT fk_pp_ct_source FOREIGN KEY (source_txn_id) REFERENCES pp_transactions (id)
);

CREATE INDEX ix_pp_ct_earner ON pp_commission_transactions (earner_account_id, created_at);
CREATE INDEX ix_pp_ct_source ON pp_commission_transactions (source_txn_id);
