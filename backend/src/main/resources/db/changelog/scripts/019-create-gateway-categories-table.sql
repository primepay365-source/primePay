-- 019: add-funds gateway categories: amount range and gateway charge % (editable by the Platform Admin).
CREATE TABLE pp_gateway_categories (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    code           VARCHAR2(20 CHAR) NOT NULL,
    name           VARCHAR2(80 CHAR) NOT NULL,
    min_amount     NUMBER(19,2) NOT NULL,
    max_amount     NUMBER(19,2) NOT NULL,
    charge_percent NUMBER(9,6)  NOT NULL,
    enabled        BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT pk_pp_gateway_categories PRIMARY KEY (id),
    CONSTRAINT uq_pp_gateway_cat_code UNIQUE (code)
);

