-- 020: one add-funds attempt through the gateway. Only the card network and last 4 digits are kept.
CREATE TABLE pp_payment_sessions (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    session_ref    VARCHAR2(40 CHAR) NOT NULL,
    account_id     NUMBER(19) NOT NULL,
    category_code  VARCHAR2(20 CHAR)  NOT NULL,
    card_network   VARCHAR2(20 CHAR)  NOT NULL,
    card_holder    VARCHAR2(160 CHAR) NOT NULL,
    card_last4     VARCHAR2(4 CHAR),
    payment_mode   VARCHAR2(10 CHAR),
    upi_masked     VARCHAR2(80 CHAR),
    amount         NUMBER(19,2) NOT NULL,
    charge         NUMBER(19,2) NOT NULL,
    net_amount     NUMBER(19,2) NOT NULL,
    otp_hash       VARCHAR2(100 CHAR),
    otp_attempts   NUMBER(10) DEFAULT 0 NOT NULL,
    status         VARCHAR2(20 CHAR) NOT NULL,
    failure_reason VARCHAR2(200 CHAR),
    gateway_ref    VARCHAR2(60 CHAR),
    transaction_id NUMBER(19),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_pp_payment_sessions PRIMARY KEY (id),
    CONSTRAINT uq_pp_ps_ref UNIQUE (session_ref),
    CONSTRAINT fk_pp_ps_account FOREIGN KEY (account_id) REFERENCES agent_account (id)
);

CREATE INDEX ix_pp_ps_account ON pp_payment_sessions (account_id);
