CREATE TABLE agent_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    account_code VARCHAR(40) NOT NULL,
    display_name VARCHAR(160) NOT NULL,
    role VARCHAR(32) NOT NULL,
    parent_id BIGINT,
    active BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_agent_account PRIMARY KEY (id),
    CONSTRAINT uq_agent_account_code UNIQUE (account_code),
    CONSTRAINT fk_agent_account_parent FOREIGN KEY (parent_id) REFERENCES agent_account(id),
    CONSTRAINT ck_agent_account_role CHECK (
        role IN ('ADMIN', 'SUPER_DISTRIBUTOR', 'MASTER_DISTRIBUTOR', 'DISTRIBUTOR', 'RETAILER')
    )
);
