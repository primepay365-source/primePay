CREATE TABLE account_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    username VARCHAR(80) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    account_id BIGINT NOT NULL,
    active BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT pk_account_user PRIMARY KEY (id),
    CONSTRAINT uq_account_user_username UNIQUE (username),
    CONSTRAINT uq_account_user_account UNIQUE (account_id),
    CONSTRAINT fk_account_user_account FOREIGN KEY (account_id) REFERENCES agent_account(id)
);
