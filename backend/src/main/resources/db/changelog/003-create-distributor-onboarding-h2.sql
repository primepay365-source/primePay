CREATE TABLE distributor_onboarding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    distributor_account_id BIGINT NOT NULL,
    created_by_account_id BIGINT NOT NULL,
    full_name VARCHAR(160) NOT NULL,
    mobile VARCHAR(20) NOT NULL,
    email VARCHAR(160) NOT NULL,
    address VARCHAR(500) NOT NULL,
    photo_content_type VARCHAR(100) NOT NULL,
    photo_data BLOB NOT NULL,
    kyc_document_type VARCHAR(32) NOT NULL,
    kyc_last_four VARCHAR(4) NOT NULL,
    bank_account_holder VARCHAR(160) NOT NULL,
    bank_name VARCHAR(120) NOT NULL,
    bank_ifsc VARCHAR(11) NOT NULL,
    bank_account_last_four VARCHAR(4) NOT NULL,
    velocity_per_transaction DECIMAL(18,2) NOT NULL,
    velocity_daily DECIMAL(18,2) NOT NULL,
    commission_payin DECIMAL(5,2) NOT NULL,
    commission_payout DECIMAL(5,2) NOT NULL,
    commission_bill_payment DECIMAL(5,2) NOT NULL,
    agreement_version VARCHAR(40) NOT NULL,
    agreement_accepted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(24) NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_distributor_onboarding PRIMARY KEY (id),
    CONSTRAINT uq_distributor_onboarding_account UNIQUE (distributor_account_id),
    CONSTRAINT fk_onboarding_distributor FOREIGN KEY (distributor_account_id) REFERENCES agent_account(id),
    CONSTRAINT fk_onboarding_creator FOREIGN KEY (created_by_account_id) REFERENCES agent_account(id),
    CONSTRAINT ck_onboarding_status CHECK (status IN ('SUBMITTED', 'APPROVED', 'REJECTED'))
);
